#!/usr/bin/env python3
"""gen_gdc_rt.py -- firmware/gdc_rt.h: np21w io/gdc_sub.c's circle table.

gdc_rt[k] = (UINT16)(32768 * (1 - sqrt(1 - (0.70710678118654*k/4096)^2))),
k = 0..4096, computed with the same double formula np21w's
gdcsub_initialize uses. Regenerate with:  python3 tools/gen_gdc_rt.py
"""
import math, os
rt = [int((1 << 15) * (1 - math.sqrt(1 - math.pow((0.70710678118654 * i) / 4096, 2))))
      for i in range(4097)]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'firmware', 'gdc_rt.h')
with open(out, 'w') as f:
    f.write('// gdc_rt.h -- generated by tools/gen_gdc_rt.py; do not edit.\n')
    f.write('// np21w io/gdc_sub.c gdc_rt[]: 32768*(1 - sqrt(1 - (0.7071*k/4096)^2)).\n')
    f.write('static const uint16_t gdc_rt_tab[4097] = {\n')
    for i in range(0, 4097, 12):
        f.write('    ' + ', '.join('%d' % v for v in rt[i:i + 12]) + ',\n')
    f.write('};\n')
